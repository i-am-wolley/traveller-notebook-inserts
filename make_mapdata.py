# -*- coding: utf-8 -*-
"""Regenerate the simplified world coastline used by the time-zone pages.

Downloads Natural Earth 110m land (public domain) and writes one simplified
outline, shared by the Python page builders and the browser booklet builder:

    map_data.py        -> POLYS, a list of [(lon, lat), ...] rings
    docs/js/mapdata.js -> the same rings for the web app

Only needed when the outline itself should change; the generated files are
committed so an ordinary build never touches the network.

    python make_mapdata.py
"""
import json
import os
import urllib.request

URL = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/"
       "master/geojson/ne_110m_land.geojson")

TOL = 0.45        # Douglas-Peucker tolerance, degrees
MIN_AREA = 4.0    # drop islands smaller than this, square degrees
LAT_FLOOR = -58   # Antarctica is cropped away, as on most world time charts


def dp(pts, tol):
    """Douglas-Peucker, on raw lon/lat degrees."""
    if len(pts) < 3:
        return pts
    x0, y0 = pts[0]
    x1, y1 = pts[-1]
    dx, dy = x1 - x0, y1 - y0
    den = dx * dx + dy * dy
    worst, at = -1.0, 0
    for i in range(1, len(pts) - 1):
        px, py = pts[i]
        if den == 0:
            d = (px - x0) ** 2 + (py - y0) ** 2
        else:
            t = max(0.0, min(1.0, ((px - x0) * dx + (py - y0) * dy) / den))
            d = (px - x0 - t * dx) ** 2 + (py - y0 - t * dy) ** 2
        if d > worst:
            worst, at = d, i
    if worst > tol * tol:
        return dp(pts[:at + 1], tol)[:-1] + dp(pts[at:], tol)
    return [pts[0], pts[-1]]


def area(pts):
    a = 0.0
    for i in range(len(pts)):
        x0, y0 = pts[i - 1]
        x1, y1 = pts[i]
        a += x0 * y1 - x1 * y0
    return abs(a) / 2.0


def rings(geom):
    t, c = geom["type"], geom["coordinates"]
    if t == "Polygon":
        return [c[0]]
    return [p[0] for p in c]


def main():
    print("fetching %s" % URL)
    raw = json.loads(urllib.request.urlopen(URL, timeout=120).read())

    out = []
    for f in raw["features"]:
        for ring in rings(f["geometry"]):
            pts = [(round(float(x), 4), round(float(y), 4)) for x, y in ring]
            if min(y for _, y in pts) < -80:
                continue                       # Antarctica
            if area(pts) < MIN_AREA:
                continue
            s = dp(pts, TOL)
            # the crop is done by the renderer's clip, but pulling the stray
            # southern tails up to the floor keeps the payload small
            s = [(x, max(y, LAT_FLOOR)) for x, y in s]
            if len(s) >= 4:
                out.append([(round(x, 2), round(y, 2)) for x, y in s])

    out.sort(key=area, reverse=True)
    pts = sum(len(r) for r in out)
    print("%d rings, %d points" % (len(out), pts))

    body = ",\n".join(
        "    [" + ",".join("(%g,%g)" % p for p in r) + "]" for r in out)
    with open("map_data.py", "w", encoding="utf-8") as fh:
        fh.write('# -*- coding: utf-8 -*-\n'
                 '"""Simplified world coastline. Generated by make_mapdata.py '
                 '- do not edit.\n\nSource: Natural Earth 110m land, public '
                 'domain. %d rings, %d points.\n"""\n\nPOLYS = [\n%s,\n]\n'
                 % (len(out), pts, body))

    jbody = ",\n".join(
        "[" + ",".join("%g,%g" % p for p in r) + "]" for r in out)
    os.makedirs(os.path.join("docs", "js"), exist_ok=True)
    with open(os.path.join("docs", "js", "mapdata.js"), "w",
              encoding="utf-8") as fh:
        fh.write("// Simplified world coastline. Generated by make_mapdata.py"
                 " - do not edit.\n"
                 "// Source: Natural Earth 110m land, public domain.\n"
                 "// Flat [lon,lat,lon,lat,...] per ring.\n"
                 "export const POLYS = [\n%s\n];\n" % jbody)

    print("wrote map_data.py and docs/js/mapdata.js")


if __name__ == "__main__":
    main()
