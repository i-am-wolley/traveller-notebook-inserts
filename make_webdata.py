# -*- coding: utf-8 -*-
"""Generate the data the browser booklet builder needs, from the Python build.

Keeps the web app honest: page geometry, A4 imposition and the sudoku pool all
come from the same code that builds the printed booklets, rather than being
retyped into JavaScript and left to drift.

    python make_webdata.py     ->  docs/js/geometry.js
                                   docs/js/metrics.js
                                   docs/js/puzzles.js

(docs/js/mapdata.js comes from make_mapdata.py, which needs the network.)
"""
import json
import os

from build_core import SIZES
from build_inserts import a4_geometry
import build_extras
import sudoku

POOL = 24          # puzzles of each grade shipped to the browser
JS = os.path.join("docs", "js")

# every character the pages can print, mapped to its WinAnsi byte
EXTRA = {"–": 0x96, "—": 0x97, "·": 0xb7, "×": 0xd7,
         "°": 0xb0, "…": 0x85, "’": 0x92, "“": 0x93,
         "”": 0x94, "−": 0x96}

FONTS = {"helv": "Helvetica", "helvB": "Helvetica-Bold",
         "times": "Times-Roman", "timesB": "Times-Bold"}


def write(name, text):
    os.makedirs(JS, exist_ok=True)
    path = os.path.join(JS, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("%-28s %6d bytes" % (path, len(text.encode("utf-8"))))


def geometry():
    sizes = {k: dict(v) for k, v in SIZES.items()}
    a4 = {k: a4_geometry(k) for k in SIZES}
    return ("// Page geometry and A4 imposition. Generated by make_webdata.py"
            " - do not edit.\n"
            "export const SIZES = %s;\n\n"
            "export const A4 = %s;\n\n"
            "export const CITIES = %s;\n\n"
            "export const SMALL_SET = %s;\n\n"
            "export const ZONES = %s;\n\n"
            "export const MONTHS = %s;\n\n"
            "export const DAYS = %s;\n"
            % (json.dumps(sizes, indent=1, sort_keys=True),
               json.dumps(a4, indent=1, sort_keys=True),
               json.dumps([list(c) for c in build_extras.CITIES]),
               json.dumps(build_extras.SMALL_SET),
               json.dumps([list(z) for z in build_extras.ZONES]),
               json.dumps(["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                           "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]),
               json.dumps([31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31])))


def metrics():
    """Advance widths for the four base-14 faces, at font size 1."""
    import pymupdf
    names = {"helv": "helv", "helvB": "hebo",
             "times": "tiro", "timesB": "tibo"}
    out = {}
    for key, short in names.items():
        f = pymupdf.Font(short)
        w = {}
        for c in range(32, 127):
            w[c] = round(f.glyph_advance(c), 4)
        for ch, code in EXTRA.items():
            w[code] = round(f.glyph_advance(ord(ch)), 4)
        out[key] = w
    return ("// Base-14 advance widths at size 1. Generated by"
            " make_webdata.py - do not edit.\n"
            "export const BASEFONT = %s;\n"
            "export const WIDTH = %s;\n"
            "export const WINANSI = %s;\n"
            % (json.dumps(FONTS),
               json.dumps(out, separators=(",", ":")),
               json.dumps({ch: code for ch, code in EXTRA.items()})))


def puzzles():
    """The pool grouped by grade, so a booklet can be one grade or a mix."""
    byg = sudoku.by_grade(POOL, build_extras.SUDOKU_SEED)
    blocks = []
    for name, _, _ in sudoku.GRADES:
        rows = ",\n  ".join(
            '["%s","%s"]' % ("".join(str(v) for v in p["puzzle"]),
                             "".join(str(v) for v in p["solution"]))
            for p in byg[name])
        blocks.append(' "%s": [\n  %s\n ]' % (name, rows))
    return ("// Sudoku pool: puzzle and solution, grouped by grade.\n"
            "// Generated by make_webdata.py - do not edit. Same generator\n"
            "// and seed as the printed booklets; every puzzle has exactly\n"
            "// one solution.\n"
            "export const GRADES = %s;\n\n"
            "export const POOL = {\n%s\n};\n"
            % (json.dumps([g[0] for g in sudoku.GRADES]),
               ",\n".join(blocks)))


def main():
    write("geometry.js", geometry())
    write("metrics.js", metrics())
    write("puzzles.js", puzzles())


if __name__ == "__main__":
    main()
